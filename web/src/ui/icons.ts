export type IconName = keyof typeof OUTLINED;

const FILLED: Partial<Record<IconName, string>> = {
  home: svgHomeFill,
  gavel: svgGavelFill,
  block: svgBlockFill,
  monitoring: svgMonitoringFill,
  group: svgGroupFill,
  fitness_center: svgFitnessCenterFill,
  settings: svgSettingsFill,
  reviews: svgReviewsFill,
  history: svgHistoryFill,
};

export const ICON_NAMES = Object.keys(OUTLINED) as IconName[];

const pathOf = (svg: string) => / d="([^"]+)"/.exec(svg)?.[1] ?? '';

/** Path data in the Material Symbols viewBox `0 -960 960 960`; filled only where a variant exists. */
export function iconPath(name: IconName, filled = false): string {
  return pathOf((filled && FILLED[name]) || OUTLINED[name]);
}
