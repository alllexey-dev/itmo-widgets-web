function renderedGrid(): string[] {
  const svg = screen.getByRole('img', { name: 'Вход на сайт' });
  const size = Number(svg.getAttribute('viewBox')?.split(' ').at(-1)) - 4;
  const rows = Array.from({ length: size }, () => Array<string>(size).fill('0'));
  const path = svg.querySelector('path')?.getAttribute('d') ?? '';
  for (const match of path.matchAll(/M(\d+) (\d+)h(\d+)v1h-\d+z/g)) {
    const [, x, y, width] = match;
    rows[Number(y) - 2]?.fill('1', Number(x) - 2, Number(x) - 2 + Number(width));
  }
  return rows.map((row) => row.join(''));
}

describe('QrCode', () => {
  it('draws the fixed module grid of the login URL at error correction M', () => {
    render(<QrCode value={LOGIN_URL} label="Вход на сайт" />);

    expect(renderedGrid()).toEqual(LEGACY_GRID);
  });
});
